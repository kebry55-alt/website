function t(key, lang) {
  const dict = translations[lang] || translations.pl;
  if (!dict) return key;
  // direct flat-key lookup (preferred)
  if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];

  // fallback to nested lookup if someone provided nested objects
  const parts = key.split('.');
  let cur = dict;
  for (const p of parts) {
    if (!cur) return key;
    cur = cur[p];
  }
  return typeof cur === 'string' ? cur : key;
}

function applyTranslations(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key, lang);
    // replace {year} placeholder if present
    const withYear = typeof text === 'string' ? text.replace('{year}', new Date().getFullYear()) : text;
    el.textContent = withYear;
  });
  // placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = t(key, lang);
    el.setAttribute('placeholder', text);
  });
  // Update aria-pressed on lang buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const is = btn.getAttribute('data-lang') === lang;
    btn.setAttribute('aria-pressed', is ? 'true' : 'false');
  });
}

// initialize after DOM ready
function initTranslations() {
  const langButtons = document.querySelectorAll('.lang-btn');
  langButtons.forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      localStorage.setItem('fundacja_lang', lang);
      applyTranslations(lang);
    });
  });

  // init language
  const saved = localStorage.getItem('fundacja_lang');
  const defaultLang = saved || (navigator.language && navigator.language.startsWith('en') ? 'en' : 'pl');
  applyTranslations(defaultLang);

  // contact form behaviour
  const form = document.querySelector('.contact-form');
  if (form) {
    form.addEventListener('submit', (event) => {
      event.preventDefault();
      const button = form.querySelector('button');
      const originalText = button.textContent;
      const lang = localStorage.getItem('fundacja_lang') || defaultLang;
      button.textContent = t('form.sent', lang);
      button.disabled = true;

      setTimeout(() => {
        button.textContent = originalText;
        button.disabled = false;
        form.reset();
      }, 2000);
    });
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initTranslations);
} else {
  initTranslations();
}
